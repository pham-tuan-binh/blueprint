#!/usr/bin/env node
// The README's pictures, made for GitHub: a banner, three figures of what a plan
// holds and a tile per example, as PNGs in .github/readme/. Every drawing and
// number comes from the examples through the kit; the 3D models are rendered by
// the plan's own viewer. Needs Playwright with Chromium.
//
//   node tools/readme.mjs
//
// Run it after a change to the examples or the kit that shows, and commit the PNGs.
import { mkdirSync, writeFileSync, rmSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SKILL = join(ROOT, 'skills/blueprint');
const OUT = join(ROOT, '.github/readme');
const imp = f => import(pathToFileURL(join(SKILL, f)).href);
const { derive } = await imp('kit/derive.mjs');
const { pageHtml, PAGE_CSS } = await imp('kit/page.mjs');
const { stepHtml, checksHtml } = await imp('kit/pack.mjs');
const { gaSheet, printSheet, jigSheet, stepViews, thumbSvg } = await imp('kit/shop.mjs');
const { esc } = await imp('kit/core.mjs');
const { bundle } = await imp('scripts/build.mjs');
const { browserOrNull, modelPng } = await import(pathToFileURL(join(ROOT, 'tools/render.mjs')).href);

const EXAMPLES = ['metal-workbench', 'pvc-drying-stand', 'shelf-rack', 'v-dipole-137'];
const W = 1280; // CSS px; every picture is this wide, drawn at 2x

const browser = await browserOrNull('no README pictures');
if (!browser) process.exit(2);
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
const tmp = mkdtempSync(join(tmpdir(), 'blueprint-readme-'));

// each example built, and its model rendered
const ex = {};
const page = await browser.newPage({ viewport: { width: W, height: 900 }, deviceScaleFactor: 2 });
for (const id of EXAMPLES) {
  const file = join(SKILL, 'examples', id, 'design.mjs');
  const plan = (await import(pathToFileURL(file).href)).plan;
  const d = derive(plan, {}, plan.units || 'metric');
  const html = join(tmp, `${id}.html`);
  writeFileSync(html, pageHtml(d, { script: bundle(file) }));
  const png = await modelPng(page, html, { size: 1000, margin: 0 });
  ex[id] = { plan, d, model: `data:image/png;base64,${png.toString('base64')}` };
  console.log(`rendered ${id}`);
}

const FIG_CSS = `
body{background:#fff}
.fig{width:${W}px;padding:56px 64px;background:#fff}
.label{font:600 13px var(--mono);letter-spacing:.12em;text-transform:uppercase;color:var(--muted);margin:0 0 18px}
.cols{display:grid;gap:56px;align-items:center}
.model{display:block;max-width:100%;max-height:100%;margin:auto}
.fig .sheet{margin:0}.fig .step{margin:0}.fig h4:first-child{margin-top:0}
.fig p,.fig li{max-width:none}
`;
const doc = (body, extra = '') => `<!doctype html><html><head><meta charset="utf-8">
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Schoolbell&display=swap" rel="stylesheet">
<style>${PAGE_CSS}${FIG_CSS}${extra}</style></head><body>${body}</body></html>`;

async function shoot(name, body, extra) {
  await page.setContent(doc(body, extra), { waitUntil: 'networkidle' });
  await page.evaluate(() => document.fonts.ready);
  await page.locator('.fig').screenshot({ path: join(OUT, `${name}.png`) });
  console.log(`wrote .github/readme/${name}.png`);
}

// banner: the name and what it does, over a faded line drawing of the workbench
await shoot('banner', `<div class="fig banner">
  <div class="bg">${thumbSvg(ex['metal-workbench'].d)}</div>
  <h1>Blueprint</h1>
  <p class="tag">Build plans for your fabrication shop, generated by your coding agent.</p>
</div>`, `
.banner{position:relative;overflow:hidden;padding:120px 96px 128px}
.banner .bg{position:absolute;right:-90px;top:-30px;width:760px;height:500px;opacity:.16}
.banner .bg svg{width:100%;height:100%;border:0;background:transparent}
.banner h1{position:relative;font:400 112px/1 "Schoolbell",cursive;margin:0 0 28px}
.banner .tag{position:relative;font:500 26px/1.35 var(--sans);margin:0;max-width:620px;color:var(--ink)}`);

// what you get: the model you resize, and the drawings it makes
const wb = ex['metal-workbench'];
await shoot('model', `<div class="fig"><div class="cols" style="grid-template-columns:1fr 1.25fr;align-items:start">
  <div><p class="label">3D model</p><div style="height:420px;display:flex;align-items:center"><img class="model" src="${wb.model}" alt=""></div></div>
  <div><p class="label">Drawings, dimensioned</p>${gaSheet(wb.d)}</div>
</div></div>`);

// a step: tasks to tick, its check and warning beside the jig, this step's parts in yellow
const st = wb.d.model.steps.find(s => s.n === 3);
const tasks = stepHtml(wb.d, st).split('<h4>Jig')[0] + '</section>';
await shoot('step', `<div class="fig"><div class="cols" style="grid-template-columns:1fr 1fr;align-items:start">
  <div><p class="label">Step ${st.n} of ${wb.d.model.steps.length}</p>${tasks}</div>
  <div><p class="label">Its jig</p>${jigSheet(wb.d, st, stepViews(wb.d, st))}</div>
</div></div>`, `.fig .step-h{margin-top:0}`);

// the checks that must pass, and a 3D-printed part drawn at its size
const ant = ex['v-dipole-137'];
const hub = ant.d.model.prints[0];
// the first 8 rows: the head, then a row per check
const checks = checksHtml(wb.d).split('<tr class="ok">').slice(0, 9).join('<tr class="ok">') + '</table></div>';
await shoot('checks', `<div class="fig"><div class="cols" style="grid-template-columns:1.2fr 1fr;align-items:start">
  <div><p class="label">Checks: ${wb.d.checks.length} of ${wb.d.checks.length} pass</p>${checks}<p class="muted">...and ${wb.d.checks.length - 8} more</p></div>
  <div><p class="label">3D-printed part: ${esc(hub.name)}</p>${printSheet(ant.d, hub)}</div>
</div></div>`);

// one tile per example, all the same size
for (const id of EXAMPLES) {
  await shoot(`example-${id}`, `<div class="fig tile"><img class="model" src="${ex[id].model}" alt=""></div>`,
    `.tile{width:520px;height:520px;padding:48px;display:flex;align-items:center;justify-content:center}`);
}

await browser.close();
rmSync(tmp, { recursive: true, force: true });
